import {unlockBrowser} from './access.mjs';
import {launch} from './browser.mjs';
import ffmpeg from 'ffmpeg-static';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
import {mkdir,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.BASE_URL||'http://127.0.0.1:8790';
assert.equal(new URL(base).hostname,'127.0.0.1','Ejecutar solo en una base local de pruebas');
await mkdir('output/video-frame',{recursive:true});
execFileSync(ffmpeg,['-y','-i','tests/fixtures/publication.mp4','-vf','pad=640:820:0:10,setsar=1','-c:v','libx264','-pix_fmt','yuv420p','-an','output/video-frame/different.mp4'],{stdio:'pipe'});
execFileSync(ffmpeg,['-y','-loop','1','-i','tests/fixtures/publication.png','-vf','scale=384:480,pad=512:640:64:80:color=0xeeeeee,format=yuv420p','-t','9','-r','10','output/video-frame/camera.y4m'],{stdio:'pipe'});
const browser=await launch(['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream',`--use-file-for-fake-video-capture=${resolve('output/video-frame/camera.y4m')}`]);
try{
  const context=await browser.newContext({viewport:{width:390,height:844},permissions:['camera']});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await unlockBrowser(page.context(),base);await page.goto(base+'/#/estudiante');await page.getByRole('button',{name:'Publicar',exact:true}).waitFor();
  await page.getByLabel('Sube tu video',{exact:true}).setInputFiles('output/video-frame/different.mp4');
  await page.getByLabel('Sube tu imagen inicial',{exact:true}).setInputFiles('tests/fixtures/publication.png');
  await page.waitForFunction(()=>{const i=document.querySelector('#image-preview'),v=document.querySelector('#video-preview');return i.complete&&v.videoWidth&&v.style.aspectRatio;});
  const preview=await page.evaluate(()=>{const i=document.querySelector('#image-preview'),v=document.querySelector('#video-preview'),r=v.getBoundingClientRect();return {image:i.naturalWidth/i.naturalHeight,video:v.videoWidth/v.videoHeight,visible:r.width/r.height,fit:getComputedStyle(v).objectFit};});
  assert.ok(Math.abs(preview.image-preview.video)/preview.image>.01,'Reproduce el fallo anterior de proporciones');
  console.log(preview);assert.ok(Math.abs(preview.visible-preview.image)<.002);assert.equal(preview.fit,'cover');
  await page.screenshot({path:'output/video-frame/preview.png',fullPage:true});
  await page.getByRole('button',{name:'Publicar',exact:true}).click();
  await page.getByRole('heading',{name:'Pieza publicada con éxito.'}).waitFor({timeout:240000});
  const state=await(await page.request.post(base+'/api/creator/session',{headers:{Origin:base},data:{}})).json();
  assert.equal(state.published,true);const id=state.submission.id;
  console.log('✓ Publicación real con imagen 640×800 y video 640×820');
  await page.getByRole('button',{name:'Ver mi pieza con realidad aumentada'}).click();
  await page.frameLocator('.scanner-overlay iframe').getByRole('button',{name:'Entendido',exact:true}).click();
  const frame=await(await page.locator('.scanner-overlay iframe').elementHandle()).contentFrame();
  await frame.waitForFunction(id=>document.body.dataset.activeWork===id&&[...document.querySelectorAll('video')].some(v=>v.getAttribute('src')===`/api/media/${id}/video`&&!v.paused&&v.currentTime>.1),id,{timeout:120000});
  await page.screenshot({path:'output/video-frame/scanner.png'});
  console.log('✓ Reconocimiento real con cámara sintética y reproducción de video');
  await frame.evaluate(()=>{parent.__fitTracks=document.querySelector('#scene video').srcObject.getTracks();});
  await page.getByRole('button',{name:'Cerrar cámara'}).click();
  await page.waitForFunction(()=>window.__fitTracks.every(t=>t.readyState==='ended'));
  assert.equal(errors.length,0,errors.join('\n'));
  await writeFile('output/video-frame/result.json',JSON.stringify({passed:true,preview,published:true,recognizedWithSyntheticCamera:true,cameraStopped:true,date:new Date().toISOString()},null,2));
}finally{await browser.close();}

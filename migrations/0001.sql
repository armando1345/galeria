PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS slots (id INTEGER PRIMARY KEY CHECK(id BETWEEN 1 AND 22), token_hash TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS submissions (id TEXT PRIMARY KEY, slot_id INTEGER NOT NULL REFERENCES slots(id), name TEXT NOT NULL, title TEXT NOT NULL, image_key TEXT NOT NULL, video_key TEXT NOT NULL, width INTEGER NOT NULL, height INTEGER NOT NULL, duration REAL NOT NULL, status TEXT NOT NULL DEFAULT 'pending', active INTEGER NOT NULL DEFAULT 1, feedback TEXT NOT NULL DEFAULT '', demo INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS submission_slot ON submissions(slot_id, created_at);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
INSERT OR IGNORE INTO settings VALUES ('closed','false');
CREATE TABLE IF NOT EXISTS sessions (hash TEXT PRIMARY KEY, role TEXT NOT NULL, slot_id INTEGER, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attempts (key TEXT PRIMARY KEY, count INTEGER NOT NULL, reset INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS publications (id TEXT PRIMARY KEY, manifest TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE IF NOT EXISTS uploads (
  id TEXT PRIMARY KEY,
  owner_hash TEXT NOT NULL,
  image_meta TEXT,
  video_meta TEXT,
  published INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS uploads_owner ON uploads(owner_hash,created_at);
